import { describe, it, expect } from 'vitest';
import { countCorrectionRounds, checkBudgetStatus, type BudgetStatus } from './budget.js';

describe('countCorrectionRounds', () => {
  it('counts 0 rounds when there are no previous reviews on the pull request', () => {
    const reviews: Array<{ user?: { login: string }; body: string }> = [];
    const count = countCorrectionRounds(reviews);
    expect(count).toBe(0);
  });

  it('counts only reviews generated by the tribunal action', () => {
    const reviews = [
      {
        user: { login: 'github-actions[bot]' },
        body: '## 🏛️ Synthetic Review Tribunal Verdict: `REQUEST_CHANGES`\nSome notes',
      },
      {
        user: { login: 'human-reviewer' },
        body: 'LGTM',
      },
      {
        user: { login: 'github-actions[bot]' },
        body: '## 🏛️ Synthetic Review Tribunal Verdict: `REQUEST_CHANGES`\nSecond round',
      },
    ];

    const count = countCorrectionRounds(reviews);
    expect(count).toBe(2);
  });
});

describe('checkBudgetStatus', () => {
  it('allows execution when correction count is strictly below max-corrections', () => {
    const status: BudgetStatus = checkBudgetStatus({
      currentCorrections: 1,
      maxCorrections: 3,
    });

    expect(status.isExhausted).toBe(false);
    expect(status.currentCorrections).toBe(1);
    expect(status.remaining).toBe(2);
  });

  it('detects exhausted budget when correction count reaches max-corrections', () => {
    const status: BudgetStatus = checkBudgetStatus({
      currentCorrections: 3,
      maxCorrections: 3,
    });

    expect(status.isExhausted).toBe(true);
    expect(status.currentCorrections).toBe(3);
    expect(status.remaining).toBe(0);
    expect(status.reason).toContain('Correction budget exhausted (3/3 rounds used)');
  });

  it('detects exhausted budget when correction count exceeds max-corrections', () => {
    const status: BudgetStatus = checkBudgetStatus({
      currentCorrections: 4,
      maxCorrections: 3,
    });

    expect(status.isExhausted).toBe(true);
    expect(status.currentCorrections).toBe(4);
    expect(status.remaining).toBe(0);
  });
});
